import { CITY_CURRENCY } from '../enums';
import { toMinor } from '../money';
import type { Event, TicketTier } from '../schemas';

type TierInput = { name: string; note: string; price: number; quantity?: number; sold?: number };

const tiers = (eventKey: string, list: TierInput[]): TicketTier[] =>
  list.map((t) => ({
    id: `tier_${eventKey}_${t.name.toLowerCase().replace(/[^a-z0-9]+/g, '_')}`,
    name: t.name,
    note: t.note,
    priceMinor: toMinor(t.price),
    quantity: t.quantity ?? null,
    sold: t.sold ?? 0,
    saleStartsAt: null,
    saleEndsAt: null,
  }));

type EventInput = Omit<Event, 'id' | 'currency' | 'coverImageUrl' | 'status' | 'tiers'> & {
  key: string;
  tiers: TierInput[];
};

const event = ({ key, tiers: tierList, ...e }: EventInput): Event => ({
  ...e,
  id: `evt_${key}`,
  currency: CITY_CURRENCY[e.city],
  coverImageUrl: null,
  status: 'live',
  tiers: tiers(key, tierList),
});

